// 最大的收获是理解了"函数式编程不是一堆花哨技巧，而是一种系统化的思维方式"。
// 最让我触动的是 pipe/compose 的管道思维——把复杂问题拆解成一系列单步转换，
// 每一步都是一个纯函数，数据像水流一样经过每个处理节点，最后得到结果。
// 这种思维方式让我意识到：好的代码不是"写得聪明"，而是"拆分得清楚"。
//
// 2. 现在你如何定义"好的代码"？
//    10 周前和现在有什么不同？
//
// 10 周前我认为"好的代码"是能跑通的代码、逻辑清晰的代码。
// 现在我会用这些标准来衡量：
//   - 纯函数优先：输入输出明确，不依赖外部状态
//   - 数据不可变：永远不修改原数据，返回新副本
//   - 函数签名清晰：从类型就能看出函数做什么
//   - 副作用隔离：I/O、DOM、网络请求集中在少数边界
//   - 可组合：小函数通过 pipe 组合成大逻辑
// 核心变化是：我从"关注代码写什么"变成了"关注数据流经哪里"。
//
// 3. 你现在的编码习惯有哪些改变？
//    比如: 还会下意识写 for 循环吗？会先考虑函数签名吗？
//
//   - 基本不再写 for/while 循环，map/filter/reduce 已经成为肌肉记忆
//   - 先想函数签名（输入什么、输出什么），再写实现
//   - 遇到数据转换时，习惯性地问"能不能用 pipe 串起来？"
//   - 区分"纯函数"和"有副作用的函数"，把副作用推到调用边界
//   - 用 Option/Either 替代 if (val === null) / try-catch 做空值和异常处理
//   - 函数参数设计时考虑柯里化，把"数据"放到最后
